// ── i18n / Localization for Ticked ───────────────────────
const SETTINGS_KEY = 'ticked_settings';
const DEFAULT_SETTINGS = { lang: 'en', headingFont: 'default', bodyFont: 'default' };
let _currentLang = 'en';

function _safeGet(k) { try { return localStorage.getItem(k); } catch { return null; } }
function _safeSet(k, v) { try { localStorage.setItem(k, v); } catch {} }

function t(key, r) {
    const dict = I18N[_currentLang] || I18N.en;
    let s = dict[key] || I18N.en[key] || key;
    if (r) Object.keys(r).forEach(k => { s = s.split('{' + k + '}').join(String(r[k])); });
    return s;
}

function loadSettings() {
    try {
        const raw = _safeGet(SETTINGS_KEY);
        return raw ? { ...DEFAULT_SETTINGS, ...JSON.parse(raw) } : { ...DEFAULT_SETTINGS };
    } catch { return { ...DEFAULT_SETTINGS }; }
}
function saveSettings(s) { _safeSet(SETTINGS_KEY, JSON.stringify(s)); }

function applySettings(settings) {
    _currentLang = settings.lang || 'en';
    document.documentElement.lang = _currentLang;
    const root = document.documentElement.style;
    const hf = settings.headingFont || 'default';
    const bf = settings.bodyFont || 'default';
    root.setProperty('--sans', hf === 'mono' ? "'IBM Plex Mono', monospace" : hf === 'system' ? "system-ui, sans-serif" : "'Syne', sans-serif");
    root.setProperty('--mono', bf === 'sans' ? "'Syne', sans-serif" : bf === 'system' ? "system-ui, sans-serif" : "'IBM Plex Mono', monospace");
    const sl = document.getElementById('settingsLang');
    const sh = document.getElementById('settingsHeadingFont');
    const sb = document.getElementById('settingsBodyFont');
    if (sl) sl.value = settings.lang;
    if (sh) sh.value = hf;
    if (sb) sb.value = bf;
    localizeStaticHTML();
}

function openSettingsModal() {
    const s = loadSettings();
    applySettings(s);
    document.getElementById('settingsModalOverlay').classList.add('open');
    document.body.classList.add('sheet-open');
}
function closeSettingsModal() {
    document.getElementById('settingsModalOverlay').classList.remove('open');
    document.body.classList.remove('sheet-open');
}
function updateSetting(key, value) {
    const s = loadSettings();
    s[key] = value;
    saveSettings(s);
    applySettings(s);
    if (typeof render === 'function') render();
}

function localizeStaticHTML() {
    document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
    document.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
    document.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
}

